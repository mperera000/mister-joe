import { motion, useReducedMotion, type TargetAndTransition, type Transition } from "motion/react";
import { useMemo } from "react";
import { JOE_ASPECT, joeSvg, type JoeMood } from "../lib/joeSvg";

/**
 * Lively Joe:
 * - listening: bobs, opens his mouth with your voice (`level`), and cups the ear on
 *   the side of the Option key you're holding (`ear`), with sound waves beside it
 * - thinking: rocks side to side while he writes it down
 * - happy: a little hop
 * Reduced motion keeps only the expression changes.
 */
export function MisterJoe({
  mood = "idle",
  size = 160,
  className = "",
  label = "Mister Joe",
  ear = null,
  level = 0,
}: {
  mood?: JoeMood;
  size?: number;
  className?: string;
  label?: string;
  ear?: "left" | "right" | null;
  level?: number;
}) {
  const reduce = useReducedMotion();
  const markup = useMemo(() => joeSvg(mood, { title: label }), [mood, label]);

  let animate: TargetAndTransition = { y: 0, rotate: 0 };
  let transition: Transition = { type: "spring", stiffness: 220, damping: 16 };
  if (!reduce) {
    if (mood === "listening") {
      animate = { y: [0, -4, 0], rotate: [0, ear === "right" ? 3 : ear === "left" ? -3 : -2, 0] };
      transition = { duration: 0.9, repeat: Infinity, ease: "easeInOut" };
    } else if (mood === "thinking") {
      animate = { rotate: [0, -5, 0, 5, 0], y: 0 };
      transition = { duration: 1.4, repeat: Infinity, ease: "easeInOut" };
    } else if (mood === "happy") {
      animate = { y: [0, -12, 0, -4, 0], rotate: 0 };
      transition = { duration: 0.7, ease: "easeOut" };
    }
  }

  return (
    <motion.div
      key={mood === "happy" ? "happy" : "joe"}
      className={`joe joe-blink shrink-0 ${mood === "listening" ? "joe-talk" : ""} ${className}`}
      data-ear={mood === "listening" ? (ear ?? undefined) : undefined}
      style={{ width: size, height: size * JOE_ASPECT, ["--joe-level" as string]: Math.min(1, level * 1.6) }}
      animate={animate}
      transition={transition}
      // Static, trusted markup generated by joeSvg.ts (no user input).
      dangerouslySetInnerHTML={{ __html: markup }}
    />
  );
}
