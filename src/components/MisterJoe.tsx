import { motion, useReducedMotion } from "motion/react";
import { useMemo } from "react";
import { JOE_ASPECT, joeSvg, type JoeMood } from "../lib/joeSvg";

export function MisterJoe({
  mood = "idle",
  size = 160,
  className = "",
  label = "Mister Joe",
}: {
  mood?: JoeMood;
  size?: number;
  className?: string;
  label?: string;
}) {
  const reduce = useReducedMotion();
  const markup = useMemo(() => joeSvg(mood, { title: label }), [mood, label]);
  // Joe bobs gently while he's listening: feedback that the mic is live.
  const bob = mood === "listening" && !reduce;
  return (
    <motion.div
      className={`joe-blink shrink-0 ${className}`}
      style={{ width: size, height: size * JOE_ASPECT }}
      animate={bob ? { y: [0, -4, 0], rotate: [0, -2, 0] } : { y: 0, rotate: 0 }}
      transition={bob ? { duration: 0.9, repeat: Infinity, ease: "easeInOut" } : { type: "spring", stiffness: 200, damping: 18 }}
      // Static, trusted markup generated by joeSvg.ts (no user input).
      dangerouslySetInnerHTML={{ __html: markup }}
    />
  );
}
